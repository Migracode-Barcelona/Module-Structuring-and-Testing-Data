// trying to create an age variable and then reassign the value by 1

const age = 33;
age = age + 1;

//AAnswer: The code will throw an error because the variable age is declared as a constant, which means its value cannot be reassigned.
// To fix this, you can declare age using let instead of const, allowing you to reassign its value.

let age = 33;
age = age + 1;

